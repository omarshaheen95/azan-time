export const LANGS: Record<Lang, Strings> = { ar, en, pt, es };
export const LANG_NAMES: Record<Lang, string> = { ar: 'العربية', en: 'English', es: 'Español', pt: 'Português' };

/** Strings for a language plus its digit and number helpers. */
export function makeText(lang: Lang, digits: 'auto' | 'eastern' | 'western') {
  const eastern = digits === 'eastern' || (digits === 'auto' && lang === 'ar');
  const d = (s: string | number) => (eastern ? String(s).replace(/[0-9]/g, (c) => EASTERN[+c]) : String(s));
  return { ...LANGS[lang], lang, eastern, d, dir: lang === 'ar' ? 'rtl' : 'ltr', locale: lang === 'pt' ? 'pt-BR' : lang === 'es' ? 'es-419' : lang };
}

export type Text = ReturnType<typeof makeText>;
